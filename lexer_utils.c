#include "minishell.h"

int	ms_is_space(char c)
{
	if (c == ' ' || c == '\t' || c == '\n')
		return (1);
	if (c == '\r' || c == '\v' || c == '\f')
		return (1);
	return (0);
}

int	ms_is_operator(char c)
{
	if (c == '|' || c == '&')
		return (1);
	if (c == '<' || c == '>')
		return (1);
	if (c == '(' || c == ')')
		return (1);
	return (0);
}
